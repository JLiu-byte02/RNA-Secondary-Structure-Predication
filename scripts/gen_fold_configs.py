#!/usr/bin/env python
"""Generate per-family ArchiveII configs from a template config.

Usage:
  python scripts/gen_fold_configs.py --template configs/exp003_5s_official_bpp.yaml \
      --outdir configs/folds --prefix method_bpp --families 5s 16s 23s tRNA srp tmRNA RNaseP grp1 telomerase
"""
from __future__ import annotations

import argparse
from pathlib import Path

import yaml

FAMILIES = ["5s", "16s", "23s", "tRNA", "srp", "tmRNA", "RNaseP", "grp1", "telomerase"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--template", required=True)
    ap.add_argument("--outdir", default="configs/folds")
    ap.add_argument("--prefix", required=True)
    ap.add_argument("--families", nargs="+", default=FAMILIES)
    ap.add_argument("--run-prefix", default=None)
    ap.add_argument("--set", action="append", default=[], help="extra dotted overrides key=value")
    args = ap.parse_args()

    template = yaml.safe_load(Path(args.template).read_text(encoding="utf-8"))
    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    for fam in args.families:
        cfg = yaml.safe_load(yaml.safe_dump(template))
        cfg["run_name"] = f"{args.run_prefix or args.prefix}_{fam}"
        cfg["data"]["train"] = {"glob": f"data/datasets/archiveii/{fam}/train.jsonl.gz"}
        cfg["data"]["select"] = {"glob": f"data/datasets/archiveii/{fam}/valid.jsonl.gz"}
        cfg["data"]["eval"] = {fam: {"glob": f"data/datasets/archiveii/{fam}/test.jsonl.gz"}}
        cfg["data"]["max_length"] = 4096
        for override in args.set:
            key, value = override.split("=", 1)
            node = cfg
            parts = key.split(".")
            for part in parts[:-1]:
                node = node[part]
            node[parts[-1]] = yaml.safe_load(value)
        path = outdir / f"{args.prefix}_{fam}.yaml"
        path.write_text(
            f"# generated by scripts/gen_fold_configs.py from {args.template} for family {fam}\n"
            + yaml.safe_dump(cfg, sort_keys=False),
            encoding="utf-8",
        )
        print("wrote", path)


if __name__ == "__main__":
    main()
